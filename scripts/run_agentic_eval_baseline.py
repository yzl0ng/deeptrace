from __future__ import annotations

import hashlib
import json
import platform
from pathlib import Path
from typing import Any

from app.evaluation.agentic import (
    AgentEvalCase,
    AgentEvalRunner,
    AgentMode,
    ScriptedComparisonProvider,
)

PROJECT_ROOT = Path(__file__).resolve().parents[1]
DATASET_DIR = (
    PROJECT_ROOT / "data" / "evaluation" / "agentic-search-v1"
)
OUTPUT_DIR = (
    PROJECT_ROOT / "data" / "experiments" / "agentic-eval-baseline-v1"
)


def main() -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    dataset_path = DATASET_DIR / "test.jsonl"
    dataset_manifest = json.loads(
        (DATASET_DIR / "manifest.json").read_text(encoding="utf-8")
    )
    dataset_hash = _sha256(dataset_path)
    if dataset_hash != dataset_manifest["test_sha256"]:
        raise RuntimeError("frozen evaluation dataset hash mismatch")
    cases = [
        AgentEvalCase.model_validate_json(line)
        for line in dataset_path.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]
    modes = [
        AgentMode.DIRECT,
        AgentMode.RAG,
        AgentMode.REACT,
        AgentMode.DEEP_RESEARCH,
    ]
    result = AgentEvalRunner(
        provider=ScriptedComparisonProvider()
    ).evaluate(
        cases,
        modes=modes,
        dataset_hash=dataset_hash,
        split="test",
    )

    config = {
        "dataset_id": dataset_manifest["dataset_id"],
        "dataset_sha256": dataset_hash,
        "split": "test",
        "cases": len(cases),
        "modes": [item.value for item in modes],
        "claim_match_threshold": 0.72,
        "provider": "scripted_comparison_v1",
        "test_used_for_tuning": False,
    }
    environment = {
        "python": platform.python_version(),
        "platform": platform.platform(),
        "network_used_during_evaluation": False,
    }
    _write_json("config.json", config)
    _write_json("environment.json", environment)
    _write_json(
        "metrics.json",
        {
            item.mode.value: item.model_dump(mode="json")
            for item in result.modes
        },
    )
    _write_jsonl(
        "predictions.jsonl",
        [item.model_dump(mode="json") for item in result.cases],
    )
    failures = [
        {
            "case_id": item.case_id,
            "dataset": item.dataset,
            "mode": item.mode.value,
            "failure_types": item.failures,
            "judgments": [
                judgment.model_dump(mode="json")
                for judgment in item.judgments
            ],
        }
        for item in result.cases
        if item.failures
    ]
    _write_jsonl("failures.jsonl", failures)
    _write_report(result)

    manifest = {
        "experiment": "agentic-eval-baseline-v1",
        "status": "completed",
        "truth_boundary": (
            "Six frozen public benchmark records and deterministic scripted "
            "mode policies; validates evaluation semantics, not model quality."
        ),
        "artifacts": {},
    }
    for path in sorted(OUTPUT_DIR.iterdir()):
        if path.name == "manifest.json":
            continue
        manifest["artifacts"][path.name] = _sha256(path)
    _write_json("manifest.json", manifest)
    print(
        json.dumps(
            {
                item.mode.value: item.metrics
                for item in result.modes
            },
            ensure_ascii=False,
            indent=2,
        )
    )


def _write_report(result: Any) -> None:
    rows = []
    for item in result.modes:
        metrics = item.metrics
        rows.append(
            "| "
            + " | ".join(
                [
                    item.mode.value,
                    f'{metrics["answer_exact_match"]:.3f}',
                    f'{metrics["citation_presence_rate"]:.3f}',
                    f'{metrics["citation_coverage"]:.3f}',
                    f'{metrics["claim_support_rate"]:.3f}',
                    f'{metrics["partial_support_rate"]:.3f}',
                    f'{metrics["unsupported_claim_rate"]:.3f}',
                    f'{metrics["invalid_citation_rate"]:.3f}',
                ]
            )
            + " |"
        )
    report = """# Agentic Evaluation Baseline v1

Status: completed

This experiment validates the Phase 4 evaluator on six frozen public
multi-hop records. The four responses are generated by deterministic scripted
policies, not real agents. The numbers must not be presented as model quality.

| Mode | Answer EM | Citation presence | Citation coverage | Claim support | Partial support | Unsupported claim | Invalid citation |
|---|---:|---:|---:|---:|---:|---:|---:|
""" + "\n".join(rows) + """

Direct produces the benchmark answer without citations. RAG cites the first
supporting fact and is therefore partial on these multi-hop cases. ReAct and
Deep Research cite all frozen supporting facts. This controlled contrast proves
that citation presence and claim support are computed independently.

The frozen test hash is checked before evaluation. No verifier threshold or mode
policy is tuned from the six test records. The Chinese draft is excluded because
it remains `reviewed=false`.
"""
    (OUTPUT_DIR / "report.md").write_text(report, encoding="utf-8")


def _write_json(name: str, payload: Any) -> None:
    (OUTPUT_DIR / name).write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )


def _write_jsonl(name: str, rows: list[dict[str, Any]]) -> None:
    (OUTPUT_DIR / name).write_text(
        "".join(
            json.dumps(item, ensure_ascii=False) + "\n"
            for item in rows
        ),
        encoding="utf-8",
    )


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


if __name__ == "__main__":
    main()
